#!/usr/bin/env python3
"""Generate executed offline evidence for Stage 4 human punch-out verification.

Runs the PO-01..PO-17 scenarios against ``MockClient`` (no model calls, no
network), captures real run-directory artifacts and audit events, and writes:

    evidence/stage4/punch_out/test_results.json
    evidence/stage4/punch_out/execution_trace.jsonl
    evidence/stage4/punch_out/approval_case.json
    evidence/stage4/punch_out/denial_case.json
    evidence/stage4/punch_out/runs/<run_id>/   (captured run directories)
    evidence/stage4/punch_out/README.md        (generated by docs step)

Mocked evidence only — kept distinct from live production evidence in
``evidence/punch_out.md`` and ``evidence/runs/``.
"""

from __future__ import annotations

import hashlib
import json
import shutil
import sys
import tempfile
from datetime import datetime, timezone
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(REPO_ROOT / "src"))
sys.path.insert(0, str(REPO_ROOT / "tests"))

from conftest import MockClient, load_json  # noqa: E402
from fictionforge.config import WorkflowConfig  # noqa: E402
from fictionforge.guardrails.punch_out import (  # noqa: E402
    DecisionError,
    load_decision,
    load_pending_decisions,
    record_human_decision,
    sign_decision,
)
from fictionforge.llm.base import LLMResponse  # noqa: E402
from fictionforge.observability.audit import AuditLogger  # noqa: E402
from fictionforge.runner import (  # noqa: E402
    WorkflowInputError,
    WorkflowRunner,
    WorkflowStatus,
)

OUT_DIR = REPO_ROOT / "evidence" / "stage4" / "punch_out"
APPROVERS = ["stage4-operator", "carol"]
KEY = b"\xab" * 32

RESULTS: list[dict] = []
TRACE: list[dict] = []


def _sha256_file(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def _code_hash() -> str:
    h = hashlib.sha256()
    for rel in (
        "src/fictionforge/runner.py",
        "src/fictionforge/guardrails/punch_out.py",
        "src/fictionforge/observability/audit.py",
        "config/workflow.yaml",
    ):
        h.update(rel.encode())
        h.update((REPO_ROOT / rel).read_bytes())
    return h.hexdigest()


def _resp(data, suffix: str = "") -> LLMResponse:
    return LLMResponse(content=json.dumps(data, ensure_ascii=False) + suffix)


def _config(workdir: Path, **kw) -> WorkflowConfig:
    key_file = workdir / "approval_signing.key"
    if not key_file.exists():
        key_file.write_text(KEY.hex() + "\n", encoding="utf-8")
    return WorkflowConfig(
        human_approvers=list(APPROVERS),
        approval_key_file=str(key_file),
        **kw,
    )


def _decide(run_dir: Path, punch_out_id: str, decision: str, approver: str):
    pendings = load_pending_decisions(run_dir)
    run_id = next(p["run_id"] for p in pendings if p["punch_out_id"] == punch_out_id)
    return record_human_decision(
        run_dir=run_dir,
        punch_out_id=punch_out_id,
        decision=decision,
        approver=approver,
        approvers=APPROVERS,
        key=KEY,
        audit=AuditLogger(run_dir, run_id=run_id),
    )


def _audit_events(run_dir: Path) -> list[dict]:
    path = run_dir / "audit.jsonl"
    if not path.exists():
        return []
    return [json.loads(line) for line in path.read_text().splitlines() if line.strip()]


def _record(scenario, *, run_dir, trigger, expected, actual, passed, extra=None):
    events = _audit_events(run_dir) if run_dir else []
    for e in events:
        TRACE.append({"scenario": scenario, **e})
    RESULTS.append(
        {
            "scenario_id": scenario,
            "run_id": (run_dir or Path(".")).name if run_dir else None,
            "trigger": trigger,
            "expected": expected,
            "actual": actual,
            "passed": bool(passed),
            "method": "mocked_offline",
            "audit_events": [e["event_type"] for e in events][-8:],
            **(extra or {}),
        }
    )


def main() -> int:
    brief_data = load_json(REPO_ROOT / "examples" / "story_brief.json")
    world_data = load_json(REPO_ROOT / "examples" / "worlds" / "valid_world.json")
    chars_data = load_json(REPO_ROOT / "examples" / "characters" / "valid_characters.json")
    story_data = load_json(REPO_ROOT / "examples" / "storyboards" / "valid_storyboard.json")

    workdir = Path(tempfile.mkdtemp(prefix="punchout-evidence-"))
    brief_path = workdir / "brief.json"
    brief_path.write_text(json.dumps(brief_data), encoding="utf-8")

    def punched_run(tag: str):
        gen = MockClient([_resp(world_data, suffix="\nskip_validation")])
        runner = WorkflowRunner(gen, _config(workdir), output_dir=workdir / tag)
        result = runner.run(brief_path)
        return runner, result

    # --- S01: trigger + halt + pending decision persisted (PO-01/02)
    runner, result = punched_run("s01")
    pid = load_pending_decisions(runner.run_dir)[0]["punch_out_id"]
    _record(
        "PO-01/02 trigger and halt",
        run_dir=runner.run_dir,
        trigger="guardrail_bypass_attempt in world_generation output",
        expected="punch_out_required; no downstream steps; pending decision persisted",
        actual=f"status={result.status.value}; steps={len(result.steps)}; pending={pid}",
        passed=(
            result.status == WorkflowStatus.PUNCH_OUT_REQUIRED
            and result.exit_code == 2
            and len(load_pending_decisions(runner.run_dir)) == 1
            and not (runner.run_dir / "characters.json").exists()
        ),
        extra={"punch_out_id": pid},
    )

    # --- S02: resume without decision (PO-03)
    r2 = WorkflowRunner(MockClient([]), _config(workdir),
                        output_dir=workdir / "s01", run_id=runner.run_id)
    try:
        r2.resume()
        actual, passed = "resumed", False
    except WorkflowInputError as exc:
        actual, passed = f"denied code={exc.code}", exc.code == "PUNCH_OUT_NOT_APPROVED"
    _record("PO-03 resume without approval", run_dir=runner.run_dir,
            trigger="resume() with no decision file",
            expected="PUNCH_OUT_NOT_APPROVED", actual=actual, passed=passed)

    # --- S03: free-text --approved-by insufficient (PO-05a)
    r3 = WorkflowRunner(MockClient([]), _config(workdir),
                        output_dir=workdir / "s01", run_id=runner.run_id)
    try:
        r3.resume(approved_by="stage4-operator")
        actual, passed = "resumed on free text", False
    except WorkflowInputError as exc:
        actual, passed = f"denied code={exc.code}", exc.code == "PUNCH_OUT_NOT_APPROVED"
    _record("PO-05 free-text approval insufficient", run_dir=runner.run_dir,
            trigger="resume(approved_by=...) with no signed decision",
            expected="PUNCH_OUT_NOT_APPROVED", actual=actual, passed=passed)

    # --- S04: invalid signature (PO-04)
    pendings = load_pending_decisions(runner.run_dir)
    forged = sign_decision(
        {
            "punch_out_id": pid, "run_id": runner.run_id, "decision": "approve",
            "approver": "stage4-operator", "step": "world_generation",
            "reason": "guardrail_bypass_attempt",
            "context_hash": pendings[0]["context_hash"],
            "decided_at": datetime.now(timezone.utc).isoformat(),
        },
        b"\xff" * 32,
    )
    (runner.run_dir / "punch_outs" / f"{pid}.decision.json").write_text(json.dumps(forged))
    r4 = WorkflowRunner(MockClient([]), _config(workdir),
                        output_dir=workdir / "s01", run_id=runner.run_id)
    try:
        r4.resume()
        actual, passed = "resumed on forged signature", False
    except WorkflowInputError as exc:
        actual, passed = f"denied code={exc.code}", exc.code == "DECISION_SIGNATURE_INVALID"
    _record("PO-04 invalid approval evidence", run_dir=runner.run_dir,
            trigger="decision file signed with wrong key",
            expected="DECISION_SIGNATURE_INVALID", actual=actual, passed=passed)
    (runner.run_dir / "punch_outs" / f"{pid}.decision.json").unlink()

    # --- S05: unlisted approver (PO-05b)
    try:
        _decide(runner.run_dir, pid, "approve", approver="mallory")
        actual, passed = "decision recorded for mallory", False
    except DecisionError as exc:
        actual, passed = f"rejected code={exc.code}", exc.code == "APPROVER_NOT_AUTHORIZED"
    _record("PO-05b forged approver identity", run_dir=runner.run_dir,
            trigger="--decide approve by unlisted approver",
            expected="APPROVER_NOT_AUTHORIZED", actual=actual, passed=passed)

    # --- S06: decision for a different run (PO-06)
    wrong_run = sign_decision(
        {
            "punch_out_id": pid, "run_id": "different-run-99", "decision": "approve",
            "approver": "stage4-operator", "step": "world_generation",
            "reason": "guardrail_bypass_attempt",
            "context_hash": pendings[0]["context_hash"],
            "decided_at": datetime.now(timezone.utc).isoformat(),
        },
        KEY,
    )
    (runner.run_dir / "punch_outs" / f"{pid}.decision.json").write_text(json.dumps(wrong_run))
    r6 = WorkflowRunner(MockClient([]), _config(workdir),
                        output_dir=workdir / "s01", run_id=runner.run_id)
    try:
        r6.resume()
        actual, passed = "resumed on wrong-run decision", False
    except WorkflowInputError as exc:
        actual, passed = f"denied code={exc.code}", exc.code == "DECISION_RUN_MISMATCH"
    _record("PO-06 approval for a different run", run_dir=runner.run_dir,
            trigger="decision bound to run_id=different-run-99",
            expected="DECISION_RUN_MISMATCH", actual=actual, passed=passed)
    (runner.run_dir / "punch_outs" / f"{pid}.decision.json").unlink()

    # --- S07: artifact modified after approval (PO-07/08)
    _decide(runner.run_dir, pid, "approve", approver="stage4-operator")
    brief = json.loads((runner.run_dir / "brief.json").read_text())
    brief["premise"] += " (modified after approval)"
    (runner.run_dir / "brief.json").write_text(json.dumps(brief))
    r7 = WorkflowRunner(MockClient([]), _config(workdir),
                        output_dir=workdir / "s01", run_id=runner.run_id)
    try:
        r7.resume()
        actual, passed = "resumed on stale context", False
    except WorkflowInputError as exc:
        actual, passed = f"denied code={exc.code}", exc.code == "DECISION_CONTEXT_MISMATCH"
    _record("PO-07/08 approval after artifact modification", run_dir=runner.run_dir,
            trigger="brief.json modified after decision recorded",
            expected="DECISION_CONTEXT_MISMATCH", actual=actual, passed=passed)
    # restore + re-decide requires fresh pending semantics; use a fresh run for approval
    (runner.run_dir / "punch_outs" / f"{pid}.decision.json").unlink()
    brief["premise"] = brief_data["premise"]
    (runner.run_dir / "brief.json").write_text(json.dumps(brief))

    # --- S08: authorized approval + resume completes (PO-09/10/16)
    runner_a, result_a = punched_run("s08")
    pid_a = load_pending_decisions(runner_a.run_dir)[0]["punch_out_id"]
    signed = _decide(runner_a.run_dir, pid_a, "approve", approver="stage4-operator")
    gen2 = MockClient([_resp(world_data), _resp(chars_data), _resp(story_data)])
    ra = WorkflowRunner(gen2, _config(workdir),
                        output_dir=workdir / "s08", run_id=runner_a.run_id)
    res_a = ra.resume(approved_by="stage4-operator")
    _record(
        "PO-09/10/16 authorized approval and resume",
        run_dir=runner_a.run_dir,
        trigger="signed approve decision; resume in a new process",
        expected="run completes; approval bound to run/context",
        actual=f"status={res_a.status.value}; approved_by="
        f"{[r.approved_by for r in res_a.punch_out_records if r.approved]}",
        passed=res_a.status == WorkflowStatus.COMPLETED,
        extra={"punch_out_id": pid_a},
    )
    approval_case = {
        "run_id": runner_a.run_id,
        "punch_out_id": pid_a,
        "pending": load_pending_decisions(runner_a.run_dir),
        "decision": load_decision(runner_a.run_dir, pid_a),
        "final_status": res_a.status.value,
        "summary_records": json.loads(
            (runner_a.run_dir / "summary.json").read_text()
        ).get("punch_out_records"),
        "signing_key_present_in_artifacts": False,
    }

    # --- S09: explicit denial, persisted + terminal (PO-11/12)
    runner_d, _ = punched_run("s09")
    pid_d = load_pending_decisions(runner_d.run_dir)[0]["punch_out_id"]
    _decide(runner_d.run_dir, pid_d, "deny", approver="carol")
    outcomes = []
    for _ in range(2):
        rd = WorkflowRunner(MockClient([]), _config(workdir),
                            output_dir=workdir / "s09", run_id=runner_d.run_id)
        try:
            rd.resume()
            outcomes.append("resumed")
        except WorkflowInputError as exc:
            outcomes.append(exc.code)
    summary_d = json.loads((runner_d.run_dir / "summary.json").read_text())
    _record(
        "PO-11/12 explicit human denial",
        run_dir=runner_d.run_dir,
        trigger="--decide deny by carol; two resume attempts",
        expected="status human_denied; every resume denied",
        actual=f"summary_status={summary_d['status']}; resumes={outcomes}",
        passed=summary_d["status"] == "human_denied"
        and outcomes == ["HUMAN_DENIED", "HUMAN_DENIED"],
        extra={"punch_out_id": pid_d},
    )
    denial_case = {
        "run_id": runner_d.run_id,
        "punch_out_id": pid_d,
        "pending": load_pending_decisions(runner_d.run_dir),
        "decision": load_decision(runner_d.run_dir, pid_d),
        "summary_status": summary_d["status"],
        "resume_attempts": outcomes,
    }

    # --- S10: security halt not approvable (PO-14)
    from fictionforge.guardrails.punch_out import (
        PunchOutReason,
        PunchOutRecord,
        write_pending_decision,
    )

    sec_dir = workdir / "s10" / "sec-run"
    sec_dir.mkdir(parents=True)
    outcomes = []
    for reason in (PunchOutReason.ARTIFACT_TAMPERED, PunchOutReason.GATE_APPROVAL_INVALID):
        p = write_pending_decision(
            sec_dir,
            PunchOutRecord(
                run_id="sec-run", step="character_design", reason=reason,
                policy="gate_approval_required", evidence={},
            ),
        )
        try:
            _decide(sec_dir, p, "approve", approver="stage4-operator")
            outcomes.append("approved")
        except DecisionError as exc:
            outcomes.append(exc.code)
    _record(
        "PO-14 security halts not approvable",
        run_dir=sec_dir,
        trigger="approve decision on artifact_tampered / gate_approval_invalid pendings",
        expected="PUNCH_OUT_NOT_APPROVABLE for both",
        actual=str(outcomes),
        passed=outcomes == ["PUNCH_OUT_NOT_APPROVABLE"] * 2,
    )

    # --- S11: replay — new punch-out needs new decision (PO-17)
    runner_r, _ = punched_run("s11")
    pid_r = load_pending_decisions(runner_r.run_dir)[0]["punch_out_id"]
    _decide(runner_r.run_dir, pid_r, "approve", approver="stage4-operator")
    gen_r = MockClient([_resp(world_data), _resp(chars_data, suffix="\nskip_validation")])
    rr = WorkflowRunner(gen_r, _config(workdir),
                        output_dir=workdir / "s11", run_id=runner_r.run_id)
    res_r = rr.resume(approved_by="stage4-operator")
    pendings_r = load_pending_decisions(runner_r.run_dir)
    rr2 = WorkflowRunner(MockClient([]), _config(workdir),
                         output_dir=workdir / "s11", run_id=runner_r.run_id)
    try:
        rr2.resume()
        second = "resumed"
    except WorkflowInputError as exc:
        second = exc.code
    _record(
        "PO-17 replayed authorization",
        run_dir=runner_r.run_dir,
        trigger="consumed approval on po-01; new punch-out po-02 during resume",
        expected="new pending requires its own decision; old one does not authorize",
        actual=f"status={res_r.status.value}; pendings={len(pendings_r)}; resume={second}",
        passed=(
            res_r.status == WorkflowStatus.PUNCH_OUT_REQUIRED
            and len(pendings_r) == 2
            and second == "PUNCH_OUT_NOT_APPROVED"
        ),
        extra={"consumed_decision": pid_r, "new_pending": pendings_r[-1]["punch_out_id"]},
    )

    # --- capture artifacts
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    (OUT_DIR / "runs").mkdir(exist_ok=True)
    for tag, src in (("approval_run", runner_a.run_dir), ("denial_run", runner_d.run_dir)):
        dst = OUT_DIR / "runs" / tag
        if dst.exists():
            shutil.rmtree(dst)
        shutil.copytree(src, dst)

    test_results = {
        "generated_at": datetime.now(timezone.utc).isoformat(),
        "method": "mocked_offline (MockClient; no model calls, no network)",
        "code_sha256": _code_hash(),
        "scenarios": RESULTS,
        "summary": {
            "total": len(RESULTS),
            "passed": sum(1 for r in RESULTS if r["passed"]),
            "failed": sum(1 for r in RESULTS if not r["passed"]),
        },
    }
    (OUT_DIR / "test_results.json").write_text(
        json.dumps(test_results, indent=2, sort_keys=True) + "\n"
    )
    with (OUT_DIR / "execution_trace.jsonl").open("w") as f:
        for e in TRACE:
            f.write(json.dumps(e, ensure_ascii=False, sort_keys=True) + "\n")
    (OUT_DIR / "approval_case.json").write_text(
        json.dumps(approval_case, indent=2, sort_keys=True) + "\n"
    )
    (OUT_DIR / "denial_case.json").write_text(
        json.dumps(denial_case, indent=2, sort_keys=True) + "\n"
    )

    print(json.dumps(test_results["summary"], indent=2))
    return 0 if all(r["passed"] for r in RESULTS) else 1


if __name__ == "__main__":
    raise SystemExit(main())
